CREATE TABLE API_LOG (
 ID BIGINT NOT NULL AUTO_INCREMENT COMMENT 'Service-local numeric primary key',
 UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Application-generated canonical audit UUID',
 PROGRAM_UUID CHAR(36) NULL COMMENT 'Program scope, absent for pre-authentication events',
 USER_UUID CHAR(36) NULL COMMENT 'Acting user public UUID',
 CUSTOMER_UUID CHAR(36) NULL COMMENT 'Affected customer public UUID',
 ACTOR_TYPE VARCHAR(32) NOT NULL COMMENT 'User, workload or system actor classification',
 ACTOR_UUID CHAR(36) NULL COMMENT 'Public actor UUID',
 SESSION_UUID CHAR(36) NULL COMMENT 'Local session public UUID',
 CORRELATION_ID VARCHAR(128) NOT NULL COMMENT 'Validated correlation identifier',
 TRACE_ID VARCHAR(64) NULL COMMENT 'Distributed tracing identifier',
 OPERATION_UUID CHAR(36) NOT NULL COMMENT 'Stable identifier shared by operation changes',
 HTTP_METHOD VARCHAR(16) NULL COMMENT 'HTTP method when applicable',
 ROUTE_TEMPLATE VARCHAR(256) NULL COMMENT 'Source route template without personal data',
 OPERATION_NAME VARCHAR(128) NOT NULL COMMENT 'Implemented business operation name',
 ENTITY_TYPE VARCHAR(128) NOT NULL COMMENT 'Affected entity classification',
 ENTITY_UUID CHAR(36) NULL COMMENT 'Affected entity public UUID',
 ACTION_CODE VARCHAR(64) NOT NULL COMMENT 'Audited action classification',
 RESULT_CODE VARCHAR(64) NOT NULL COMMENT 'Safe operation result classification',
 HTTP_STATUS_CODE SMALLINT NULL COMMENT 'HTTP response code when applicable',
 DURATION_MS BIGINT NULL COMMENT 'Elapsed operation duration in milliseconds',
 CHANGE_DETAILS JSON NULL COMMENT 'Allowlisted field differences excluding secrets',
 CREATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC audit creation timestamp',
 PRIMARY KEY (ID), UNIQUE KEY UX_API_LOG_UUID (UUID),
 KEY IX_API_LOG_OPERATION (OPERATION_UUID), KEY IX_API_LOG_PROGRAM_CREATED (PROGRAM_UUID, CREATED_DATETIME)
) ENGINE=InnoDB COMMENT='Append-only business and security audit owned by this service';

CREATE TABLE ERROR_LOGS (
 ID BIGINT NOT NULL AUTO_INCREMENT COMMENT 'Service-local numeric primary key',
 UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Application-generated canonical error UUID',
 PROGRAM_UUID CHAR(36) NULL COMMENT 'Program scope when known',
 CORRELATION_ID VARCHAR(128) NOT NULL COMMENT 'Validated correlation identifier',
 TRACE_ID VARCHAR(64) NULL COMMENT 'Distributed tracing identifier',
 OPERATION_UUID CHAR(36) NULL COMMENT 'Related business operation UUID',
 SERVICE_NAME VARCHAR(64) NOT NULL COMMENT 'Originating service name',
 ERROR_CODE VARCHAR(64) NOT NULL COMMENT 'Stable safe error code',
 ERROR_CATEGORY VARCHAR(64) NOT NULL COMMENT 'Validation, security, dependency or unexpected category',
 SEVERITY VARCHAR(16) NOT NULL COMMENT 'Operational error severity',
 SAFE_MESSAGE VARCHAR(512) NOT NULL COMMENT 'Redacted human-readable description',
 REDACTED_DETAILS JSON NULL COMMENT 'Allowlisted diagnostic context without secrets',
 EXCEPTION_TYPE VARCHAR(256) NULL COMMENT 'Exception classification when applicable',
 STACK_TRACE TEXT NULL COMMENT 'Redacted restricted stack trace; absent for expected failures',
 CREATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC error occurrence timestamp',
 PRIMARY KEY (ID), UNIQUE KEY UX_ERROR_LOGS_UUID (UUID),
 KEY IX_ERROR_LOGS_CORRELATION (CORRELATION_ID)
) ENGINE=InnoDB COMMENT='Restricted append-only error records independent of business transaction rollback';