-- Identity Management owns identity linkage, memberships and authentication sessions.
CREATE TABLE USER_ACCOUNT (
 ID BIGINT NOT NULL AUTO_INCREMENT COMMENT 'Service-local numeric primary key',
 UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Canonical lowercase public UUID generated by the application',
 ISSUER VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Exact allowlisted OIDC issuer identifier',
 SUBJECT VARCHAR(255) COLLATE utf8mb4_0900_bin NOT NULL COMMENT 'Exact opaque provider subject identifier',
 EMAIL VARCHAR(254) NOT NULL COMMENT 'Latest verified provider email for display; never used for automatic account linkage',
 EMAIL_VERIFIED BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Last observed provider email verification claim; revalidate during login',
 IS_ENABLED BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Whether the local identity is permitted to authenticate',
 CREATED_BY_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'User or workload UUID that created the record',
 CREATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC creation timestamp',
 UPDATED_BY_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'User or workload UUID that last changed the record',
 UPDATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC last business update timestamp',
 ROW_VERSION BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT 'Application-managed optimistic concurrency counter incremented on each update',
 PRIMARY KEY (ID),
 UNIQUE KEY UX_USER_ACCOUNT_UUID (UUID),
 CONSTRAINT CK_USER_ACCOUNT_VERSION CHECK (ROW_VERSION > 0),
 CONSTRAINT CK_USER_ACCOUNT_METADATA_TIME CHECK (UPDATED_DATETIME >= CREATED_DATETIME),
 UNIQUE KEY UX_USER_ACCOUNT_PROVIDER (ISSUER,SUBJECT),
 CONSTRAINT CK_USER_ACCOUNT_FLAGS CHECK (EMAIL_VERIFIED IN (0,1) AND IS_ENABLED IN (0,1)),
 CONSTRAINT CK_USER_ACCOUNT_LINK CHECK (CHAR_LENGTH(ISSUER) > 0 AND CHAR_LENGTH(SUBJECT) > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='Local identity linked by verified provider issuer and subject; no password or token storage';
CREATE TABLE MEMBERSHIP (
 ID BIGINT NOT NULL AUTO_INCREMENT COMMENT 'Service-local numeric primary key',
 UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Canonical lowercase public UUID generated by the application',
 USER_ACCOUNT_ID BIGINT NOT NULL COMMENT 'Local foreign key to USER_ACCOUNT.ID',
 PROGRAM_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Core PROGRAM.UUID; no cross-service database foreign key',
 STATUS VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'SUSPENDED' COMMENT 'ACTIVE, SUSPENDED or REVOKED membership state',
 CREATED_BY_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'User or workload UUID that created the record',
 CREATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC creation timestamp',
 UPDATED_BY_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'User or workload UUID that last changed the record',
 UPDATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC last business update timestamp',
 ROW_VERSION BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT 'Application-managed optimistic concurrency counter incremented on each update',
 PRIMARY KEY (ID),
 UNIQUE KEY UX_MEMBERSHIP_UUID (UUID),
 CONSTRAINT CK_MEMBERSHIP_VERSION CHECK (ROW_VERSION > 0),
 CONSTRAINT CK_MEMBERSHIP_METADATA_TIME CHECK (UPDATED_DATETIME >= CREATED_DATETIME),
 UNIQUE KEY UX_MEMBERSHIP_USER_PROGRAM (USER_ACCOUNT_ID,PROGRAM_UUID),
 UNIQUE KEY UX_MEMBERSHIP_SCOPE (ID,PROGRAM_UUID,USER_ACCOUNT_ID),
 CONSTRAINT FK_MEMBERSHIP_USER FOREIGN KEY (USER_ACCOUNT_ID) REFERENCES USER_ACCOUNT (ID),
 CONSTRAINT CK_MEMBERSHIP_STATUS CHECK (STATUS IN ('ACTIVE','SUSPENDED','REVOKED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='Program access grant owned by Identity Management';
CREATE TABLE MEMBERSHIP_PERMISSION (
 ID BIGINT NOT NULL AUTO_INCREMENT COMMENT 'Service-local numeric primary key',
 UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Canonical lowercase public UUID generated by the application',
 MEMBERSHIP_ID BIGINT NOT NULL COMMENT 'Local foreign key to MEMBERSHIP.ID; permissions inherit its Program scope',
 PERMISSION_CODE VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Allowlisted implemented permission code such as CUSTOMERS.PROFILE.READ',
 IS_ENABLED BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Whether this permission grant is active',
 CREATED_BY_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'User or workload UUID that created the record',
 CREATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC creation timestamp',
 UPDATED_BY_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'User or workload UUID that last changed the record',
 UPDATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC last business update timestamp',
 ROW_VERSION BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT 'Application-managed optimistic concurrency counter incremented on each update',
 PRIMARY KEY (ID),
 UNIQUE KEY UX_MEMBERSHIP_PERMISSION_UUID (UUID),
 CONSTRAINT CK_MEMBERSHIP_PERMISSION_VERSION CHECK (ROW_VERSION > 0),
 CONSTRAINT CK_MEMBERSHIP_PERMISSION_METADATA_TIME CHECK (UPDATED_DATETIME >= CREATED_DATETIME),
 UNIQUE KEY UX_MEMBERSHIP_PERMISSION_CODE (MEMBERSHIP_ID,PERMISSION_CODE),
 CONSTRAINT FK_MEMBERSHIP_PERMISSION_MEMBER FOREIGN KEY (MEMBERSHIP_ID) REFERENCES MEMBERSHIP (ID),
 CONSTRAINT CK_MEMBERSHIP_PERMISSION_ENABLED CHECK (IS_ENABLED IN (0,1)),
 CONSTRAINT CK_MEMBERSHIP_PERMISSION_CODE CHECK (CHAR_LENGTH(PERMISSION_CODE) > 0 AND PERMISSION_CODE = UPPER(PERMISSION_CODE))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='Explicit implemented permission grant for a Program membership';
CREATE TABLE AUTH_SESSION (
 ID BIGINT NOT NULL AUTO_INCREMENT COMMENT 'Service-local numeric primary key',
 UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Canonical lowercase public UUID generated by the application',
 MEMBERSHIP_ID BIGINT NOT NULL COMMENT 'Local membership authorizing this Program session',
 PROGRAM_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Program UUID bound to membership and user by the composite foreign key',
 USER_ACCOUNT_ID BIGINT NOT NULL COMMENT 'Local user bound to the same membership and Program',
 OPERATION_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Stable login operation UUID shared with Core',
 CORE_SESSION_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT 'Core application-session UUID after creation acknowledgement',
 PROVIDER_SESSION_HASH BINARY(32) NULL COMMENT 'Digest of provider session identifier for correlation; not a bearer credential',
 STATE VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING, ACTIVE, REVOKED or EXPIRED authentication state',
 AUTHENTICATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC time of verified provider authentication',
 ACTIVATED_DATETIME DATETIME(6) NULL COMMENT 'UTC activation after pending Core session acknowledgement',
 LAST_ACTIVITY_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC last authoritative authorized activity',
 EXPIRES_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC absolute expiry bounded by provider policy',
 REVOKED_DATETIME DATETIME(6) NULL COMMENT 'UTC authoritative revocation time',
 REVOCATION_REASON_CODE VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT 'Safe reason classification such as CUSTOMER_LOGOUT',
 CREATED_BY_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'User or workload UUID that created the record',
 CREATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC creation timestamp',
 UPDATED_BY_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'User or workload UUID that last changed the record',
 UPDATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC last business update timestamp',
 ROW_VERSION BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT 'Application-managed optimistic concurrency counter incremented on each update',
 PRIMARY KEY (ID),
 UNIQUE KEY UX_AUTH_SESSION_UUID (UUID),
 CONSTRAINT CK_AUTH_SESSION_VERSION CHECK (ROW_VERSION > 0),
 CONSTRAINT CK_AUTH_SESSION_METADATA_TIME CHECK (UPDATED_DATETIME >= CREATED_DATETIME),
 UNIQUE KEY UX_AUTH_SESSION_OPERATION (OPERATION_UUID),
 UNIQUE KEY UX_AUTH_SESSION_CORE (CORE_SESSION_UUID),
 KEY IX_AUTH_SESSION_MEMBERSHIP (MEMBERSHIP_ID,PROGRAM_UUID,USER_ACCOUNT_ID),
 KEY IX_AUTH_SESSION_EXPIRY (STATE,EXPIRES_DATETIME),
 CONSTRAINT FK_AUTH_SESSION_MEMBERSHIP FOREIGN KEY (MEMBERSHIP_ID,PROGRAM_UUID,USER_ACCOUNT_ID) REFERENCES MEMBERSHIP (ID,PROGRAM_UUID,USER_ACCOUNT_ID),
 CONSTRAINT CK_AUTH_SESSION_STATE CHECK (STATE IN ('PENDING','ACTIVE','REVOKED','EXPIRED')),
 CONSTRAINT CK_AUTH_SESSION_ACTIVE CHECK (STATE <> 'ACTIVE' OR (CORE_SESSION_UUID IS NOT NULL AND ACTIVATED_DATETIME IS NOT NULL)),
 CONSTRAINT CK_AUTH_SESSION_REVOKED CHECK ((STATE = 'REVOKED' AND REVOKED_DATETIME IS NOT NULL) OR (STATE <> 'REVOKED' AND REVOKED_DATETIME IS NULL)),
 CONSTRAINT CK_AUTH_SESSION_TIME CHECK (EXPIRES_DATETIME > CREATED_DATETIME AND AUTHENTICATED_DATETIME <= CREATED_DATETIME AND LAST_ACTIVITY_DATETIME >= CREATED_DATETIME AND LAST_ACTIVITY_DATETIME <= EXPIRES_DATETIME AND (ACTIVATED_DATETIME IS NULL OR (ACTIVATED_DATETIME >= CREATED_DATETIME AND ACTIVATED_DATETIME < EXPIRES_DATETIME)))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='Program-scoped authentication session controlled by Identity Management';
CREATE TABLE SESSION_WORKFLOW (
 ID BIGINT NOT NULL AUTO_INCREMENT COMMENT 'Service-local numeric primary key',
 UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Canonical lowercase public UUID generated by the application',
 AUTH_SESSION_ID BIGINT NOT NULL COMMENT 'Local authentication session being coordinated',
 OPERATION_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Stable operation UUID for idempotent downstream recovery',
 ACTION_CODE VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'ACTIVATE or REVOKE coordination action',
 STATE VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING, RUNNING, COMPLETED or MANUAL_REVIEW recovery state',
 ATTEMPT_COUNT INT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Bounded recovery attempt count; bookkeeping is not recursive business audit',
 NEXT_ATTEMPT_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC earliest next recovery attempt',
 LEASE_OWNER_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT 'Workload UUID holding the recovery lease',
 LEASE_EXPIRES_DATETIME DATETIME(6) NULL COMMENT 'UTC lease expiry used with optimistic concurrency for crash recovery',
 LAST_ERROR_CODE VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT 'Safe failure code; diagnostics belong to ERROR_LOGS',
 CREATED_BY_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'User or workload UUID that created the record',
 CREATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC creation timestamp',
 UPDATED_BY_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'User or workload UUID that last changed the record',
 UPDATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC last business update timestamp',
 ROW_VERSION BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT 'Application-managed optimistic concurrency counter incremented on each update',
 PRIMARY KEY (ID),
 UNIQUE KEY UX_SESSION_WORKFLOW_UUID (UUID),
 CONSTRAINT CK_SESSION_WORKFLOW_VERSION CHECK (ROW_VERSION > 0),
 CONSTRAINT CK_SESSION_WORKFLOW_METADATA_TIME CHECK (UPDATED_DATETIME >= CREATED_DATETIME),
 UNIQUE KEY UX_SESSION_WORKFLOW_OPERATION (OPERATION_UUID),
 UNIQUE KEY UX_SESSION_WORKFLOW_ACTION (AUTH_SESSION_ID,ACTION_CODE),
 KEY IX_SESSION_WORKFLOW_DUE (STATE,NEXT_ATTEMPT_DATETIME),
 CONSTRAINT FK_SESSION_WORKFLOW_AUTH FOREIGN KEY (AUTH_SESSION_ID) REFERENCES AUTH_SESSION (ID),
 CONSTRAINT CK_SESSION_WORKFLOW_ACTION CHECK (ACTION_CODE IN ('ACTIVATE','REVOKE')),
 CONSTRAINT CK_SESSION_WORKFLOW_STATE CHECK (STATE IN ('PENDING','RUNNING','COMPLETED','MANUAL_REVIEW')),
 CONSTRAINT CK_SESSION_WORKFLOW_LEASE CHECK ((STATE = 'RUNNING' AND LEASE_OWNER_UUID IS NOT NULL AND LEASE_EXPIRES_DATETIME IS NOT NULL) OR (STATE <> 'RUNNING' AND LEASE_OWNER_UUID IS NULL AND LEASE_EXPIRES_DATETIME IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='Durable activation or revocation recovery owned by Identity Management';
