CREATE TABLE SESSION_REVOCATION_OUTBOX (
 ID BIGINT NOT NULL AUTO_INCREMENT COMMENT 'Core-local numeric primary key',
 UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Public recovery-operation UUID',
 CORE_SESSION_ID BIGINT NOT NULL COMMENT 'Local Core session requiring authoritative remote revocation',
 AUTH_SESSION_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Identity Management authentication-session UUID',
 OPERATION_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Stable idempotent logout operation UUID',
 STATE VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING, COMPLETED or MANUAL_REVIEW recovery state',
 ATTEMPT_COUNT INT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Technical recovery attempt count',
 NEXT_ATTEMPT_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC earliest next remote revocation attempt',
 CREATED_BY_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'User or workload creating recovery work',
 CREATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC creation time',
 UPDATED_BY_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'User or workload performing the last state change',
 UPDATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC last state change',
 ROW_VERSION BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT 'Application-managed concurrency version',
 PRIMARY KEY (ID), UNIQUE KEY UX_SESSION_REVOCATION_UUID (UUID),
 UNIQUE KEY UX_SESSION_REVOCATION_CORE (CORE_SESSION_ID),
 CONSTRAINT FK_SESSION_REVOCATION_CORE FOREIGN KEY (CORE_SESSION_ID) REFERENCES CORE_SESSION (ID),
 CONSTRAINT CK_SESSION_REVOCATION_STATE CHECK (STATE IN ('PENDING','COMPLETED','MANUAL_REVIEW'))
) ENGINE=InnoDB COMMENT='Durable logout recovery when Identity Management cannot be reached';