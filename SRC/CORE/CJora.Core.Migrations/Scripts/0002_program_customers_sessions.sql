-- Core-owned identity/session schema. No cross-service foreign keys or credential storage.
CREATE TABLE PROGRAM (
 ID BIGINT NOT NULL AUTO_INCREMENT COMMENT 'Service-local numeric primary key',
 UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Canonical lowercase public UUID generated by the application',
 PROGRAM_KEY VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Stable lowercase Program resolution key',
 DISPLAY_NAME VARCHAR(160) NOT NULL COMMENT 'Customer-visible Program name',
 IS_ENABLED BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Whether the Program may authorize application access',
 CREATED_BY_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'User or workload UUID that created the record',
 CREATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC creation timestamp',
 UPDATED_BY_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'User or workload UUID that last changed the record',
 UPDATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC last business update timestamp',
 ROW_VERSION BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT 'Application-managed optimistic concurrency counter incremented on each update',
 PRIMARY KEY (ID),
 UNIQUE KEY UX_PROGRAM_UUID (UUID),
 CONSTRAINT CK_PROGRAM_VERSION CHECK (ROW_VERSION > 0),
 CONSTRAINT CK_PROGRAM_METADATA_TIME CHECK (UPDATED_DATETIME >= CREATED_DATETIME),
 UNIQUE KEY UX_PROGRAM_KEY (PROGRAM_KEY),
 CONSTRAINT CK_PROGRAM_ENABLED CHECK (IS_ENABLED IN (0,1)),
 CONSTRAINT CK_PROGRAM_KEY CHECK (CHAR_LENGTH(PROGRAM_KEY) BETWEEN 1 AND 64 AND PROGRAM_KEY = LOWER(PROGRAM_KEY))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='Program tenancy root owned by Core';
CREATE TABLE CUSTOMER (
 ID BIGINT NOT NULL AUTO_INCREMENT COMMENT 'Service-local numeric primary key',
 UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Canonical lowercase public UUID generated by the application',
 PROGRAM_ID BIGINT NOT NULL COMMENT 'Local foreign key to PROGRAM.ID',
 USER_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Identity Management USER_ACCOUNT.UUID; never its numeric ID',
 DISPLAY_NAME VARCHAR(160) NOT NULL COMMENT 'Approved customer display name',
 EMAIL VARCHAR(254) NOT NULL COMMENT 'Customer contact email; never an identity linkage key',
 STATUS VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'RESTRICTED' COMMENT 'ACTIVE or RESTRICTED customer access state',
 CREATED_BY_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'User or workload UUID that created the record',
 CREATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC creation timestamp',
 UPDATED_BY_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'User or workload UUID that last changed the record',
 UPDATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC last business update timestamp',
 ROW_VERSION BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT 'Application-managed optimistic concurrency counter incremented on each update',
 PRIMARY KEY (ID),
 UNIQUE KEY UX_CUSTOMER_UUID (UUID),
 CONSTRAINT CK_CUSTOMER_VERSION CHECK (ROW_VERSION > 0),
 CONSTRAINT CK_CUSTOMER_METADATA_TIME CHECK (UPDATED_DATETIME >= CREATED_DATETIME),
 UNIQUE KEY UX_CUSTOMER_PROGRAM_USER (PROGRAM_ID,USER_UUID),
 UNIQUE KEY UX_CUSTOMER_SCOPE (ID,PROGRAM_ID,USER_UUID),
 CONSTRAINT FK_CUSTOMER_PROGRAM FOREIGN KEY (PROGRAM_ID) REFERENCES PROGRAM (ID),
 CONSTRAINT CK_CUSTOMER_STATUS CHECK (STATUS IN ('ACTIVE','RESTRICTED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='Program-scoped customer profile owned by Core';
CREATE TABLE CORE_SESSION (
 ID BIGINT NOT NULL AUTO_INCREMENT COMMENT 'Service-local numeric primary key',
 UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Canonical lowercase public UUID generated by the application',
 PROGRAM_ID BIGINT NOT NULL COMMENT 'Local Program scope bound to the customer composite foreign key',
 CUSTOMER_ID BIGINT NOT NULL COMMENT 'Local customer ID bound to the same Program and user',
 USER_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Identity Management user UUID bound to the customer',
 AUTH_SESSION_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Linked Identity Management authentication-session UUID',
 OPERATION_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Stable idempotent login workflow UUID shared across services',
 SESSION_SECRET_HASH BINARY(32) NULL COMMENT 'SHA256 digest of a cryptographically random browser secret; never the raw cookie',
 STATE VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING, ACTIVE, REVOKED or EXPIRED session state',
 ACTIVATED_DATETIME DATETIME(6) NULL COMMENT 'UTC activation confirmation time; null while pending',
 LAST_ACTIVITY_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC last authorized activity time',
 EXPIRES_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC absolute expiry no later than the linked authentication session',
 REVOKED_DATETIME DATETIME(6) NULL COMMENT 'UTC local revocation time',
 REVOCATION_REASON_CODE VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT 'Safe revocation classification without personal data',
 CREATED_BY_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'User or workload UUID that created the record',
 CREATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC creation timestamp',
 UPDATED_BY_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'User or workload UUID that last changed the record',
 UPDATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC last business update timestamp',
 ROW_VERSION BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT 'Application-managed optimistic concurrency counter incremented on each update',
 PRIMARY KEY (ID),
 UNIQUE KEY UX_CORE_SESSION_UUID (UUID),
 CONSTRAINT CK_CORE_SESSION_VERSION CHECK (ROW_VERSION > 0),
 CONSTRAINT CK_CORE_SESSION_METADATA_TIME CHECK (UPDATED_DATETIME >= CREATED_DATETIME),
 UNIQUE KEY UX_CORE_SESSION_OPERATION (OPERATION_UUID),
 UNIQUE KEY UX_CORE_SESSION_AUTH (AUTH_SESSION_UUID),
 UNIQUE KEY UX_CORE_SESSION_SECRET (SESSION_SECRET_HASH),
 KEY IX_CORE_SESSION_CUSTOMER (CUSTOMER_ID,PROGRAM_ID,USER_UUID),
 KEY IX_CORE_SESSION_EXPIRY (STATE,EXPIRES_DATETIME),
 CONSTRAINT FK_CORE_SESSION_CUSTOMER FOREIGN KEY (CUSTOMER_ID,PROGRAM_ID,USER_UUID) REFERENCES CUSTOMER (ID,PROGRAM_ID,USER_UUID),
 CONSTRAINT CK_CORE_SESSION_STATE CHECK (STATE IN ('PENDING','ACTIVE','REVOKED','EXPIRED')),
 CONSTRAINT CK_CORE_SESSION_ACTIVE CHECK (STATE <> 'ACTIVE' OR (ACTIVATED_DATETIME IS NOT NULL AND SESSION_SECRET_HASH IS NOT NULL)),
 CONSTRAINT CK_CORE_SESSION_REVOKED CHECK ((STATE = 'REVOKED' AND REVOKED_DATETIME IS NOT NULL) OR (STATE <> 'REVOKED' AND REVOKED_DATETIME IS NULL)),
 CONSTRAINT CK_CORE_SESSION_TIME CHECK (EXPIRES_DATETIME > CREATED_DATETIME AND LAST_ACTIVITY_DATETIME >= CREATED_DATETIME AND LAST_ACTIVITY_DATETIME <= EXPIRES_DATETIME AND (ACTIVATED_DATETIME IS NULL OR (ACTIVATED_DATETIME >= CREATED_DATETIME AND ACTIVATED_DATETIME < EXPIRES_DATETIME)))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='Application session linked to an authoritative Identity Management authentication session';
