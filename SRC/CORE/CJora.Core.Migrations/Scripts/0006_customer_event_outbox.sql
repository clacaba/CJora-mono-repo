CREATE TABLE CUSTOMER_EVENT_OUTBOX (
 ID BIGINT NOT NULL AUTO_INCREMENT COMMENT 'Core-local numeric primary key',
 UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Stable event UUID reused on every publication attempt',
 CUSTOMER_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Core customer UUID and Kafka ordering key',
 SOURCE_VERSION BIGINT NOT NULL COMMENT 'Customer version captured atomically with the business update',
 OPERATION_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Idempotent customer write or reconciliation operation',
 OPERATION_HASH BINARY(32) NOT NULL COMMENT 'SHA256 of the canonical command; no raw personal data',
 PAYLOAD JSON NOT NULL COMMENT 'Allowlisted version-one identifier and status snapshot; no contact information',
 STATE VARCHAR(16) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING, LEASED, PUBLISHED or MANUAL_REVIEW',
 ATTEMPT_COUNT INT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Publication claims; maximum ten automatic attempts',
 NEXT_ATTEMPT_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC earliest publication retry',
 LEASE_OWNER_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT 'Unique claimant that may acknowledge this attempt',
 LEASE_EXPIRES_DATETIME DATETIME(6) NULL COMMENT 'UTC expiration for crash recovery',
 PUBLISHED_DATETIME DATETIME(6) NULL COMMENT 'UTC successful broker acknowledgement time',
 CREATED_BY_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Actor creating this event',
 CREATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC event persistence time',
 UPDATED_BY_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Workload or actor last changing delivery state',
 UPDATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC last delivery state change',
 ROW_VERSION BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT 'Delivery state concurrency version',
 PRIMARY KEY (ID), UNIQUE KEY UX_CUSTOMER_OUTBOX_UUID (UUID),
 UNIQUE KEY UX_CUSTOMER_OUTBOX_VERSION (CUSTOMER_UUID,SOURCE_VERSION),
 UNIQUE KEY UX_CUSTOMER_OUTBOX_OPERATION (OPERATION_UUID),
 KEY IX_CUSTOMER_OUTBOX_DUE (STATE,NEXT_ATTEMPT_DATETIME),
 CONSTRAINT CK_CUSTOMER_OUTBOX_VERSION CHECK (SOURCE_VERSION>0),
 CONSTRAINT CK_CUSTOMER_OUTBOX_STATE CHECK (STATE IN ('PENDING','LEASED','PUBLISHED','MANUAL_REVIEW')),
 CONSTRAINT CK_CUSTOMER_OUTBOX_LEASE CHECK ((STATE='LEASED' AND LEASE_OWNER_UUID IS NOT NULL AND LEASE_EXPIRES_DATETIME IS NOT NULL) OR (STATE<>'LEASED' AND LEASE_OWNER_UUID IS NULL AND LEASE_EXPIRES_DATETIME IS NULL))
) ENGINE=InnoDB COMMENT='Transactional customer snapshot outbox owned by Core; publication is at least once';
