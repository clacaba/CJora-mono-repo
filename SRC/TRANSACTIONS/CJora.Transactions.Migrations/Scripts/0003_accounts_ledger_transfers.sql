CREATE DEFINER='cjora_tx_finance_definer'@'%' PROCEDURE FINANCE_INTENT_BODY(IN p_id BIGINT,OUT p_body JSON)
SQL SECURITY DEFINER
BEGIN
 SELECT JSON_OBJECT('intentUuid',I.UUID,'state',I.STATE,'reviewVersion',I.REVIEW_VERSION,
 'sourceAccountUuid',S.UUID,'destinationAccountUuid',D.UUID,'destinationLabel',D.LABEL,
 'amount',JSON_OBJECT('currency',I.CURRENCY,'minorUnits',CAST(I.AMOUNT_MINOR AS CHAR)),
 'feeMinor','0','totalDebitMinor',CAST(I.AMOUNT_MINOR AS CHAR),'reference',I.REFERENCE_TEXT,
 'expiresAtUtc',DATE_FORMAT(I.EXPIRES_DATETIME,'%Y-%m-%dT%H:%i:%s.%fZ'),'transferUuid',T.UUID,'failureCode',I.FAILURE_CODE)
 INTO p_body FROM TRANSFER_INTENT I JOIN ACCOUNT S ON S.ID=I.SOURCE_ACCOUNT_ID JOIN ACCOUNT D ON D.ID=I.DESTINATION_ACCOUNT_ID
 LEFT JOIN TRANSFER T ON T.TRANSFER_INTENT_ID=I.ID WHERE I.ID=p_id;
END;

