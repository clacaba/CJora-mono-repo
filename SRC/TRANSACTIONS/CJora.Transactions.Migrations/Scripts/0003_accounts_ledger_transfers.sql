CREATE DEFINER='cjora_tx_finance_definer'@'%' PROCEDURE FINANCE_PREPARE(
 IN p_program CHAR(36),IN p_customer CHAR(36),IN p_user CHAR(36),IN p_core CHAR(36),IN p_auth CHAR(36),
 IN p_authorized DATETIME(6),IN p_session_expires DATETIME(6),IN p_key CHAR(36),IN p_hash BINARY(32),
 IN p_intent CHAR(36),IN p_source CHAR(36),IN p_destination CHAR(36),IN p_currency CHAR(3),
 IN p_amount BIGINT,IN p_reference VARCHAR(140))
SQL SECURITY DEFINER
main: BEGIN
 DECLARE v_request BIGINT; DECLARE v_request_uuid CHAR(36); DECLARE v_hash BINARY(32); DECLARE v_request_state VARCHAR(16);
 DECLARE v_source BIGINT DEFAULT NULL; DECLARE v_destination BIGINT DEFAULT NULL; DECLARE v_dummy BIGINT;
 DECLARE v_source_owner CHAR(36); DECLARE v_source_status VARCHAR(16); DECLARE v_destination_status VARCHAR(16);
 DECLARE v_source_currency CHAR(3); DECLARE v_destination_currency CHAR(3);
 DECLARE v_source_type VARCHAR(32); DECLARE v_destination_type VARCHAR(32);
 DECLARE v_source_customer_status VARCHAR(16); DECLARE v_destination_customer_status VARCHAR(16);
 DECLARE v_balance BIGINT; DECLARE v_destination_balance BIGINT; DECLARE v_limit BIGINT DEFAULT NULL; DECLARE v_enabled BOOLEAN DEFAULT FALSE;
 DECLARE v_now DATETIME(6); DECLARE v_intent_id BIGINT; DECLARE v_body JSON; DECLARE v_status INT DEFAULT 201;
 DECLARE v_error VARCHAR(64) DEFAULT NULL; DECLARE v_missing INT DEFAULT 0;
 DECLARE CONTINUE HANDLER FOR NOT FOUND SET v_missing=1;
 DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;
 SET v_now=UTC_TIMESTAMP(6);
 IF p_amount IS NULL OR p_amount<=0 OR p_reference IS NULL OR p_reference NOT REGEXP '^[ -~]{0,140}$' OR p_source=p_destination THEN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='INVALID_TRANSFER_REQUEST';
 END IF;
 IF p_authorized IS NULL OR p_session_expires IS NULL OR p_session_expires<=v_now OR p_authorized>DATE_ADD(v_now,INTERVAL 1 SECOND)
 OR TIMESTAMPDIFF(MICROSECOND,p_authorized,v_now)>=30000000 THEN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='FINANCIAL_AUTHORITY_EXPIRED';
 END IF;
 START TRANSACTION;
 INSERT INTO FINANCIAL_REQUEST(UUID,PROGRAM_UUID,CUSTOMER_UUID,OPERATION_CODE,IDEMPOTENCY_KEY,PAYLOAD_HASH,INTENT_UUID,
 CREATED_BY_UUID,CREATED_DATETIME,UPDATED_BY_UUID,UPDATED_DATETIME)
 VALUES(UUID(),p_program,p_customer,'PREPARE',p_key,p_hash,p_intent,p_user,v_now,p_user,v_now)
 ON DUPLICATE KEY UPDATE ID=LAST_INSERT_ID(ID);
 SET v_request=LAST_INSERT_ID();
 SELECT UUID,PAYLOAD_HASH,STATE,HTTP_STATUS,RESPONSE_BODY INTO v_request_uuid,v_hash,v_request_state,v_status,v_body
 FROM FINANCIAL_REQUEST WHERE ID=v_request FOR UPDATE;
 IF v_hash<>p_hash THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='IDEMPOTENCY_CONFLICT'; END IF;
 IF v_request_state='COMPLETED' THEN
  COMMIT; SELECT IF(v_status=201,200,v_status) AS HTTP_STATUS,v_body AS RESPONSE_BODY,TRUE AS IS_REPLAY; LEAVE main;
 END IF;
 SELECT ID INTO v_source FROM ACCOUNT WHERE UUID=p_source AND PROGRAM_UUID=p_program AND CUSTOMER_UUID=p_customer AND ACCOUNT_TYPE='CUSTOMER_LIABILITY';
 SELECT ID INTO v_destination FROM ACCOUNT WHERE UUID=p_destination AND PROGRAM_UUID=p_program AND ACCOUNT_TYPE='CUSTOMER_LIABILITY';
 IF v_source IS NULL OR v_destination IS NULL THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='RESOURCE_NOT_AVAILABLE'; END IF;
 SELECT IS_ENABLED,MAX_TRANSFER_MINOR INTO v_enabled,v_limit FROM PROGRAM_FINANCIAL_POLICY
 WHERE PROGRAM_UUID=p_program AND CURRENCY=p_currency AND DEMO_ONLY=1 FOR SHARE;
 SELECT ID INTO v_dummy FROM ACCOUNT WHERE ID=LEAST(v_source,v_destination) FOR UPDATE;
 SELECT ID INTO v_dummy FROM ACCOUNT WHERE ID=GREATEST(v_source,v_destination) FOR UPDATE;
 SELECT A.CUSTOMER_UUID,A.STATUS,A.CURRENCY,A.ACCOUNT_TYPE,A.POSTED_MINOR,R.STATUS
 INTO v_source_owner,v_source_status,v_source_currency,v_source_type,v_balance,v_source_customer_status
 FROM ACCOUNT A JOIN CUSTOMER_REFERENCE R ON R.UUID=A.CUSTOMER_UUID AND R.PROGRAM_UUID=A.PROGRAM_UUID WHERE A.ID=v_source FOR UPDATE OF A;
 SELECT A.STATUS,A.CURRENCY,A.ACCOUNT_TYPE,A.POSTED_MINOR,R.STATUS
 INTO v_destination_status,v_destination_currency,v_destination_type,v_destination_balance,v_destination_customer_status
 FROM ACCOUNT A JOIN CUSTOMER_REFERENCE R ON R.UUID=A.CUSTOMER_UUID AND R.PROGRAM_UUID=A.PROGRAM_UUID WHERE A.ID=v_destination FOR UPDATE OF A;
 SET v_now=UTC_TIMESTAMP(6);
 IF p_session_expires<=v_now OR TIMESTAMPDIFF(MICROSECOND,p_authorized,v_now)>=30000000 THEN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='FINANCIAL_AUTHORITY_EXPIRED';
 END IF;
 IF v_limit IS NULL OR v_enabled=FALSE THEN SET v_error='CURRENCY_NOT_ENABLED';
 ELSEIF v_source_currency<>p_currency OR v_destination_currency<>p_currency THEN SET v_error='CURRENCY_MISMATCH';
 ELSEIF v_source_status<>'ACTIVE' OR v_destination_status<>'ACTIVE' OR v_source_customer_status<>'ACTIVE' OR v_destination_customer_status<>'ACTIVE' THEN SET v_error='ACCOUNT_RESTRICTED';
 ELSEIF p_amount>v_limit THEN SET v_error='TRANSFER_LIMIT_EXCEEDED';
 ELSEIF p_amount>v_balance THEN SET v_error='INSUFFICIENT_FUNDS';
 ELSEIF v_destination_balance>9223372036854775807-p_amount THEN SET v_error='BALANCE_LIMIT_EXCEEDED';
 END IF;
 IF v_error IS NOT NULL THEN
  SET v_status=422; CALL FINANCE_PROBLEM(v_error,v_status,v_request_uuid,NULL,v_body);
  CALL FINANCE_AUDIT(v_request_uuid,p_program,p_user,p_core,NULL,'TRANSFER_PREPARATION_REJECTED',v_error,'DENIED');
 ELSE
  SET v_status=201;
  INSERT INTO TRANSFER_INTENT(UUID,PROGRAM_UUID,CUSTOMER_UUID,USER_UUID,CORE_SESSION_UUID,AUTH_SESSION_UUID,SOURCE_ACCOUNT_ID,DESTINATION_ACCOUNT_ID,
  CURRENCY,AMOUNT_MINOR,REFERENCE_TEXT,TERMS_HASH,EXPIRES_DATETIME,CREATED_BY_UUID,CREATED_DATETIME,UPDATED_BY_UUID,UPDATED_DATETIME)
  VALUES(p_intent,p_program,p_customer,p_user,p_core,p_auth,v_source,v_destination,p_currency,p_amount,p_reference,p_hash,
  DATE_ADD(v_now,INTERVAL 5 MINUTE),p_user,v_now,p_user,v_now);
  SET v_intent_id=LAST_INSERT_ID(); CALL FINANCE_INTENT_BODY(v_intent_id,v_body);
  CALL FINANCE_AUDIT(v_request_uuid,p_program,p_user,p_core,p_intent,'TRANSFER_INTENT_PREPARED','PREPARED','SUCCEEDED');
 END IF;
 UPDATE FINANCIAL_REQUEST SET STATE='COMPLETED',HTTP_STATUS=v_status,RESPONSE_BODY=v_body,UPDATED_DATETIME=v_now,ROW_VERSION=ROW_VERSION+1 WHERE ID=v_request;
 COMMIT;
 SELECT v_status AS HTTP_STATUS,v_body AS RESPONSE_BODY,FALSE AS IS_REPLAY;
END;

CREATE DEFINER='cjora_tx_finance_definer'@'%' PROCEDURE FINANCE_CONFIRM(
 IN p_program CHAR(36),IN p_customer CHAR(36),IN p_user CHAR(36),IN p_core CHAR(36),IN p_auth CHAR(36),
 IN p_authorized DATETIME(6),IN p_session_expires DATETIME(6),IN p_key CHAR(36),IN p_hash BINARY(32),
 IN p_intent CHAR(36),IN p_terms BINARY(32),IN p_review INT)
SQL SECURITY DEFINER
main: BEGIN
 DECLARE v_request BIGINT; DECLARE v_request_uuid CHAR(36); DECLARE v_hash BINARY(32); DECLARE v_request_state VARCHAR(16);
 DECLARE v_intent BIGINT DEFAULT NULL; DECLARE v_owner CHAR(36); DECLARE v_user CHAR(36); DECLARE v_core CHAR(36); DECLARE v_auth CHAR(36);
 DECLARE v_state VARCHAR(16); DECLARE v_failure VARCHAR(64); DECLARE v_expires DATETIME(6); DECLARE v_terms BINARY(32);
 DECLARE v_source BIGINT; DECLARE v_destination BIGINT; DECLARE v_dummy BIGINT;
 DECLARE v_source_uuid CHAR(36); DECLARE v_destination_uuid CHAR(36); DECLARE v_destination_customer CHAR(36);
 DECLARE v_source_owner CHAR(36); DECLARE v_source_status VARCHAR(16); DECLARE v_destination_status VARCHAR(16);
 DECLARE v_source_currency CHAR(3); DECLARE v_destination_currency CHAR(3); DECLARE v_currency CHAR(3);
 DECLARE v_source_customer_status VARCHAR(16); DECLARE v_destination_customer_status VARCHAR(16);
 DECLARE v_amount BIGINT; DECLARE v_balance BIGINT; DECLARE v_destination_balance BIGINT; DECLARE v_limit BIGINT DEFAULT NULL;
 DECLARE v_s_sequence BIGINT; DECLARE v_d_sequence BIGINT; DECLARE v_enabled BOOLEAN DEFAULT FALSE;
 DECLARE v_reference VARCHAR(140); DECLARE v_transfer BIGINT; DECLARE v_transfer_uuid CHAR(36); DECLARE v_journal BIGINT;
 DECLARE v_now DATETIME(6); DECLARE v_body JSON; DECLARE v_status INT DEFAULT 201;
 DECLARE v_error VARCHAR(64) DEFAULT NULL; DECLARE v_missing INT DEFAULT 0;
 DECLARE CONTINUE HANDLER FOR NOT FOUND SET v_missing=1;
 DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;
 SET v_now=UTC_TIMESTAMP(6);
 IF p_review IS NULL OR p_review<>1 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='INVALID_REVIEW_VERSION'; END IF;
 IF p_authorized IS NULL OR p_session_expires IS NULL OR p_session_expires<=v_now OR p_authorized>DATE_ADD(v_now,INTERVAL 1 SECOND)
 OR TIMESTAMPDIFF(MICROSECOND,p_authorized,v_now)>=30000000 THEN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='FINANCIAL_AUTHORITY_EXPIRED';
 END IF;
 START TRANSACTION;
 INSERT INTO FINANCIAL_REQUEST(UUID,PROGRAM_UUID,CUSTOMER_UUID,OPERATION_CODE,IDEMPOTENCY_KEY,PAYLOAD_HASH,INTENT_UUID,
 CREATED_BY_UUID,CREATED_DATETIME,UPDATED_BY_UUID,UPDATED_DATETIME)
 VALUES(UUID(),p_program,p_customer,'CONFIRM',p_key,p_hash,p_intent,p_user,v_now,p_user,v_now)
 ON DUPLICATE KEY UPDATE ID=LAST_INSERT_ID(ID);
 SET v_request=LAST_INSERT_ID();
 SELECT UUID,PAYLOAD_HASH,STATE,HTTP_STATUS,RESPONSE_BODY INTO v_request_uuid,v_hash,v_request_state,v_status,v_body
 FROM FINANCIAL_REQUEST WHERE ID=v_request FOR UPDATE;
 IF v_hash<>p_hash THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='IDEMPOTENCY_CONFLICT'; END IF;
 IF v_request_state='COMPLETED' THEN
  COMMIT; SELECT IF(v_status=201,200,v_status) AS HTTP_STATUS,v_body AS RESPONSE_BODY,TRUE AS IS_REPLAY; LEAVE main;
 END IF;
 SELECT ID,CUSTOMER_UUID,USER_UUID,CORE_SESSION_UUID,AUTH_SESSION_UUID,STATE,FAILURE_CODE,EXPIRES_DATETIME,TERMS_HASH,
 SOURCE_ACCOUNT_ID,DESTINATION_ACCOUNT_ID,CURRENCY,AMOUNT_MINOR,REFERENCE_TEXT
 INTO v_intent,v_owner,v_user,v_core,v_auth,v_state,v_failure,v_expires,v_terms,v_source,v_destination,v_currency,v_amount,v_reference
 FROM TRANSFER_INTENT WHERE UUID=p_intent AND PROGRAM_UUID=p_program AND CUSTOMER_UUID=p_customer FOR UPDATE;
 IF v_intent IS NULL OR v_owner<>p_customer OR v_user<>p_user THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='RESOURCE_NOT_AVAILABLE'; END IF;
 IF v_terms<>p_terms THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='REVIEW_TERMS_CHANGED'; END IF;
 IF v_state='POSTED' THEN
  SELECT ID INTO v_transfer FROM TRANSFER WHERE TRANSFER_INTENT_ID=v_intent;
  CALL FINANCE_RECEIPT_BODY(v_transfer,v_body); SET v_status=200;
 ELSEIF v_state IN ('REJECTED','EXPIRED') THEN
  SET v_status=IF(v_state='EXPIRED',409,422); CALL FINANCE_PROBLEM(v_failure,v_status,v_request_uuid,p_intent,v_body);
 ELSE
  IF v_core<>p_core OR v_auth<>p_auth THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='REVIEW_SESSION_CHANGED'; END IF;
  SELECT IS_ENABLED,MAX_TRANSFER_MINOR INTO v_enabled,v_limit FROM PROGRAM_FINANCIAL_POLICY
  WHERE PROGRAM_UUID=p_program AND CURRENCY=v_currency AND DEMO_ONLY=1 FOR SHARE;
  SELECT ID INTO v_dummy FROM ACCOUNT WHERE ID=LEAST(v_source,v_destination) FOR UPDATE;
  SELECT ID INTO v_dummy FROM ACCOUNT WHERE ID=GREATEST(v_source,v_destination) FOR UPDATE;
  SELECT A.UUID,A.CUSTOMER_UUID,A.STATUS,A.CURRENCY,A.POSTED_MINOR,A.LAST_ENTRY_SEQUENCE,R.STATUS
  INTO v_source_uuid,v_source_owner,v_source_status,v_source_currency,v_balance,v_s_sequence,v_source_customer_status
  FROM ACCOUNT A JOIN CUSTOMER_REFERENCE R ON R.UUID=A.CUSTOMER_UUID AND R.PROGRAM_UUID=A.PROGRAM_UUID
  WHERE A.ID=v_source AND A.PROGRAM_UUID=p_program AND A.ACCOUNT_TYPE='CUSTOMER_LIABILITY' FOR UPDATE OF A;
  SELECT A.UUID,A.CUSTOMER_UUID,A.STATUS,A.CURRENCY,A.POSTED_MINOR,A.LAST_ENTRY_SEQUENCE,R.STATUS
  INTO v_destination_uuid,v_destination_customer,v_destination_status,v_destination_currency,v_destination_balance,v_d_sequence,v_destination_customer_status
  FROM ACCOUNT A JOIN CUSTOMER_REFERENCE R ON R.UUID=A.CUSTOMER_UUID AND R.PROGRAM_UUID=A.PROGRAM_UUID
  WHERE A.ID=v_destination AND A.PROGRAM_UUID=p_program AND A.ACCOUNT_TYPE='CUSTOMER_LIABILITY' FOR UPDATE OF A;
  SET v_now=UTC_TIMESTAMP(6);
  IF p_session_expires<=v_now OR TIMESTAMPDIFF(MICROSECOND,p_authorized,v_now)>=30000000 THEN
   SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='FINANCIAL_AUTHORITY_EXPIRED';
  END IF;
  IF v_source_owner IS NULL OR v_source_owner<>p_customer OR v_destination_customer IS NULL OR v_source=v_destination THEN
   SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='RESOURCE_NOT_AVAILABLE';
  END IF;
  IF v_expires<=v_now THEN SET v_error='TRANSFER_REVIEW_EXPIRED'; SET v_status=409; SET v_state='EXPIRED';
  ELSEIF v_limit IS NULL OR v_enabled=FALSE THEN SET v_error='CURRENCY_NOT_ENABLED';
  ELSEIF v_source_currency<>v_currency OR v_destination_currency<>v_currency THEN SET v_error='CURRENCY_MISMATCH';
  ELSEIF v_source_status<>'ACTIVE' OR v_destination_status<>'ACTIVE' OR v_source_customer_status<>'ACTIVE' OR v_destination_customer_status<>'ACTIVE' THEN SET v_error='ACCOUNT_RESTRICTED';
  ELSEIF v_amount<=0 OR v_amount>v_limit THEN SET v_error='TRANSFER_LIMIT_EXCEEDED';
  ELSEIF v_balance<v_amount THEN SET v_error='INSUFFICIENT_FUNDS';
  ELSEIF v_destination_balance>9223372036854775807-v_amount THEN SET v_error='BALANCE_LIMIT_EXCEEDED';
  ELSEIF v_s_sequence=9223372036854775807 OR v_d_sequence=9223372036854775807 THEN SET v_error='ACCOUNT_SEQUENCE_LIMIT_EXCEEDED';
  END IF;
  IF v_error IS NOT NULL THEN
   IF v_state<>'EXPIRED' THEN SET v_state='REJECTED'; SET v_status=422; END IF;
   UPDATE TRANSFER_INTENT SET STATE=v_state,FAILURE_CODE=v_error,UPDATED_BY_UUID=p_user,UPDATED_DATETIME=v_now,ROW_VERSION=ROW_VERSION+1 WHERE ID=v_intent;
   CALL FINANCE_PROBLEM(v_error,v_status,v_request_uuid,p_intent,v_body);
   CALL FINANCE_AUDIT(v_request_uuid,p_program,p_user,p_core,p_intent,'TRANSFER_CONFIRMATION_REJECTED',v_error,'DENIED');
  ELSE
   SET v_transfer_uuid=UUID();
   INSERT INTO TRANSFER(UUID,PROGRAM_UUID,TRANSFER_INTENT_ID,SOURCE_ACCOUNT_ID,DESTINATION_ACCOUNT_ID,CURRENCY,AMOUNT_MINOR,REFERENCE_TEXT,POSTED_DATETIME,CREATED_BY_UUID,CREATED_DATETIME)
   VALUES(v_transfer_uuid,p_program,v_intent,v_source,v_destination,v_currency,v_amount,v_reference,v_now,p_user,v_now);
   SET v_transfer=LAST_INSERT_ID();
   INSERT INTO LEDGER_JOURNAL(UUID,PROGRAM_UUID,CURRENCY,TRANSFER_ID,OPERATION_UUID,JOURNAL_TYPE,DEBIT_TOTAL_MINOR,CREDIT_TOTAL_MINOR,POSTED_DATETIME,CREATED_BY_UUID,CREATED_DATETIME)
   VALUES(UUID(),p_program,v_currency,v_transfer,v_request_uuid,'INTERNAL_TRANSFER',v_amount,v_amount,v_now,p_user,v_now);
   SET v_journal=LAST_INSERT_ID();
   INSERT INTO LEDGER_ENTRY(UUID,JOURNAL_ID,ACCOUNT_ID,PROGRAM_UUID,CURRENCY,SIDE,AMOUNT_MINOR,ENTRY_SEQUENCE,CREATED_BY_UUID,CREATED_DATETIME)
   VALUES(UUID(),v_journal,v_source,p_program,v_currency,'DEBIT',v_amount,v_s_sequence+1,p_user,v_now),
         (UUID(),v_journal,v_destination,p_program,v_currency,'CREDIT',v_amount,v_d_sequence+1,p_user,v_now);
   UPDATE ACCOUNT SET POSTED_MINOR=POSTED_MINOR-v_amount,LAST_ENTRY_SEQUENCE=LAST_ENTRY_SEQUENCE+1,UPDATED_BY_UUID=p_user,UPDATED_DATETIME=v_now,ROW_VERSION=ROW_VERSION+1 WHERE ID=v_source;
   UPDATE ACCOUNT SET POSTED_MINOR=POSTED_MINOR+v_amount,LAST_ENTRY_SEQUENCE=LAST_ENTRY_SEQUENCE+1,UPDATED_BY_UUID=p_user,UPDATED_DATETIME=v_now,ROW_VERSION=ROW_VERSION+1 WHERE ID=v_destination;
   UPDATE TRANSFER_INTENT SET STATE='POSTED',UPDATED_BY_UUID=p_user,UPDATED_DATETIME=v_now,ROW_VERSION=ROW_VERSION+1 WHERE ID=v_intent;
   INSERT INTO FINANCIAL_EVENT_OUTBOX(UUID,PROGRAM_UUID,TRANSFER_UUID,EVENT_TYPE,PAYLOAD,CREATED_BY_UUID,CREATED_DATETIME,UPDATED_BY_UUID,UPDATED_DATETIME)
   VALUES(UUID(),p_program,v_transfer_uuid,'transactions.transfer.posted.v1',
   JSON_OBJECT('transferUuid',v_transfer_uuid,'programUuid',p_program,'sourceCustomerUuid',p_customer,'destinationCustomerUuid',v_destination_customer,'state','POSTED'),
   p_user,v_now,p_user,v_now);
   CALL FINANCE_AUDIT(v_request_uuid,p_program,p_user,p_core,v_transfer_uuid,'TRANSFER_POSTED','POSTED','SUCCEEDED');
   CALL FINANCE_RECEIPT_BODY(v_transfer,v_body); SET v_status=201;
  END IF;
 END IF;
 UPDATE FINANCIAL_REQUEST SET STATE='COMPLETED',HTTP_STATUS=v_status,RESPONSE_BODY=v_body,UPDATED_DATETIME=UTC_TIMESTAMP(6),ROW_VERSION=ROW_VERSION+1 WHERE ID=v_request;
 COMMIT;
 SELECT v_status AS HTTP_STATUS,v_body AS RESPONSE_BODY,FALSE AS IS_REPLAY;
END;

CREATE DEFINER='cjora_tx_finance_definer'@'%' PROCEDURE FINANCE_RECONCILE(IN p_account CHAR(36))
SQL SECURITY DEFINER
main: BEGIN
 DECLARE v_id BIGINT DEFAULT NULL; DECLARE v_balance BIGINT; DECLARE v_sequence BIGINT; DECLARE v_type VARCHAR(32);
 DECLARE v_program CHAR(36); DECLARE v_total DECIMAL(65,0); DECLARE v_count BIGINT; DECLARE v_max BIGINT;
 DECLARE v_bad BIGINT; DECLARE v_op CHAR(36); DECLARE v_status VARCHAR(16); DECLARE v_missing INT;
 DECLARE CONTINUE HANDLER FOR NOT FOUND SET v_missing=1;
 DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;
 START TRANSACTION;
 SELECT ID,PROGRAM_UUID,POSTED_MINOR,LAST_ENTRY_SEQUENCE,ACCOUNT_TYPE,STATUS INTO v_id,v_program,v_balance,v_sequence,v_type,v_status
 FROM ACCOUNT WHERE UUID=p_account FOR UPDATE;
 IF v_id IS NULL THEN COMMIT; LEAVE main; END IF;
 SELECT COALESCE(SUM(CASE WHEN (v_type='CUSTOMER_LIABILITY' AND SIDE='CREDIT') OR (v_type='DEMO_CLEARING_ASSET' AND SIDE='DEBIT') THEN AMOUNT_MINOR ELSE -AMOUNT_MINOR END),0),
 COUNT(*),COALESCE(MAX(ENTRY_SEQUENCE),0) INTO v_total,v_count,v_max FROM LEDGER_ENTRY WHERE ACCOUNT_ID=v_id;
 SELECT COUNT(*) INTO v_bad FROM LEDGER_JOURNAL J WHERE J.ID IN (SELECT JOURNAL_ID FROM LEDGER_ENTRY WHERE ACCOUNT_ID=v_id)
 AND ((SELECT COUNT(*) FROM LEDGER_ENTRY E WHERE E.JOURNAL_ID=J.ID)<>2
 OR (SELECT COALESCE(SUM(E.AMOUNT_MINOR),0) FROM LEDGER_ENTRY E WHERE E.JOURNAL_ID=J.ID AND E.SIDE='DEBIT')<>J.DEBIT_TOTAL_MINOR
 OR (SELECT COALESCE(SUM(E.AMOUNT_MINOR),0) FROM LEDGER_ENTRY E WHERE E.JOURNAL_ID=J.ID AND E.SIDE='CREDIT')<>J.CREDIT_TOTAL_MINOR);
 IF v_total<>v_balance OR v_count<>v_sequence OR v_max<>v_sequence OR v_bad>0 THEN
  IF v_status<>'RESTRICTED' THEN
   SET v_op=UUID();
   UPDATE ACCOUNT SET STATUS='RESTRICTED',UPDATED_BY_UUID='00000000-0000-0000-0000-000000000001',UPDATED_DATETIME=UTC_TIMESTAMP(6),ROW_VERSION=ROW_VERSION+1 WHERE ID=v_id;
   CALL FINANCE_AUDIT(v_op,v_program,NULL,NULL,p_account,'ACCOUNT_RECONCILIATION_RESTRICTED','RESTRICTED','DENIED');
   INSERT INTO ERROR_LOGS(UUID,PROGRAM_UUID,CORRELATION_ID,OPERATION_UUID,SERVICE_NAME,ERROR_CODE,ERROR_CATEGORY,SEVERITY,SAFE_MESSAGE,CREATED_DATETIME)
   VALUES(UUID(),v_program,v_op,v_op,'Transactions','LEDGER_RECONCILIATION_FAILED','INTEGRITY','ERROR','Account restricted pending ledger investigation.',UTC_TIMESTAMP(6));
  END IF;
 END IF;
 COMMIT;
END;
