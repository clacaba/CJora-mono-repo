CREATE TABLE ACCOUNT_INTEGRITY_ALERT (
 ID BIGINT NOT NULL AUTO_INCREMENT COMMENT 'Transactions-local numeric integrity alert key',
 UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Public integrity investigation reference',
 ACCOUNT_ID BIGINT NOT NULL COMMENT 'Local ledger account requiring investigation',
 STATE VARCHAR(16) NOT NULL DEFAULT 'MANUAL_REVIEW' COMMENT 'MANUAL_REVIEW or explicit operator RESOLVED state; never automatically cleared',
 ERROR_CODE VARCHAR(64) NOT NULL COMMENT 'Safe integrity failure classification',
 CREATED_BY_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Workload that first recorded the alert',
 CREATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC first detection time',
 UPDATED_BY_UUID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'Workload or operator last changing the alert',
 UPDATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC last alert state transition',
 ROW_VERSION BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT 'Integrity review concurrency version',
 PRIMARY KEY (ID), UNIQUE KEY UX_ACCOUNT_INTEGRITY_UUID (UUID),
 UNIQUE KEY UX_ACCOUNT_INTEGRITY_ACCOUNT (ACCOUNT_ID),
 CONSTRAINT FK_ACCOUNT_INTEGRITY_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES ACCOUNT (ID),
 CONSTRAINT CK_ACCOUNT_INTEGRITY_STATE CHECK (STATE IN ('MANUAL_REVIEW','RESOLVED'))
) ENGINE=InnoDB COMMENT='Durable deduplicated ledger investigation, including accounts already restricted or closed';

DROP PROCEDURE FINANCE_RECONCILE;
CREATE DEFINER='cjora_tx_finance_definer'@'%' PROCEDURE FINANCE_RECONCILE(IN p_account CHAR(36))
SQL SECURITY DEFINER
main: BEGIN
 DECLARE v_id BIGINT DEFAULT NULL; DECLARE v_balance BIGINT; DECLARE v_sequence BIGINT; DECLARE v_type VARCHAR(32);
 DECLARE v_program CHAR(36); DECLARE v_total DECIMAL(65,0); DECLARE v_count BIGINT; DECLARE v_max BIGINT;
 DECLARE v_bad BIGINT; DECLARE v_op CHAR(36); DECLARE v_status VARCHAR(16); DECLARE v_missing INT;
 DECLARE v_alert BIGINT DEFAULT NULL; DECLARE v_alert_state VARCHAR(16);
 DECLARE CONTINUE HANDLER FOR NOT FOUND SET v_missing=1;
 DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;
 START TRANSACTION;
 SELECT ID,PROGRAM_UUID,POSTED_MINOR,LAST_ENTRY_SEQUENCE,ACCOUNT_TYPE,STATUS INTO v_id,v_program,v_balance,v_sequence,v_type,v_status
 FROM ACCOUNT WHERE UUID=p_account FOR UPDATE;
 IF v_id IS NULL THEN COMMIT; LEAVE main; END IF;
 SELECT COALESCE(SUM(CASE WHEN (v_type='CUSTOMER_LIABILITY' AND SIDE='CREDIT') OR (v_type='DEMO_CLEARING_ASSET' AND SIDE='DEBIT') THEN AMOUNT_MINOR ELSE -AMOUNT_MINOR END),0),
 COUNT(*),COALESCE(MAX(ENTRY_SEQUENCE),0) INTO v_total,v_count,v_max FROM LEDGER_ENTRY WHERE ACCOUNT_ID=v_id;
 SELECT COUNT(*) INTO v_bad FROM LEDGER_JOURNAL J WHERE J.ID IN (SELECT JOURNAL_ID FROM LEDGER_ENTRY WHERE ACCOUNT_ID=v_id)
 AND ((SELECT COUNT(*) FROM LEDGER_ENTRY E WHERE E.JOURNAL_ID=J.ID)<>2
 OR (SELECT COALESCE(SUM(E.AMOUNT_MINOR),0) FROM LEDGER_ENTRY E WHERE E.JOURNAL_ID=J.ID AND E.SIDE='DEBIT')<>J.DEBIT_TOTAL_MINOR
 OR (SELECT COALESCE(SUM(E.AMOUNT_MINOR),0) FROM LEDGER_ENTRY E WHERE E.JOURNAL_ID=J.ID AND E.SIDE='CREDIT')<>J.CREDIT_TOTAL_MINOR);
 IF v_total<>v_balance OR v_count<>v_sequence OR v_max<>v_sequence OR v_bad>0 THEN
  SET v_op=UUID();
  IF v_status='ACTIVE' THEN
   UPDATE ACCOUNT SET STATUS='RESTRICTED',UPDATED_BY_UUID='00000000-0000-0000-0000-000000000001',UPDATED_DATETIME=UTC_TIMESTAMP(6),ROW_VERSION=ROW_VERSION+1 WHERE ID=v_id;
   CALL FINANCE_AUDIT(v_op,v_program,NULL,NULL,p_account,'ACCOUNT_RECONCILIATION_RESTRICTED','RESTRICTED','DENIED');
  END IF;
  SELECT ID,STATE INTO v_alert,v_alert_state FROM ACCOUNT_INTEGRITY_ALERT WHERE ACCOUNT_ID=v_id FOR UPDATE;
  IF v_alert IS NULL THEN
   INSERT INTO ACCOUNT_INTEGRITY_ALERT(UUID,ACCOUNT_ID,STATE,ERROR_CODE,CREATED_BY_UUID,CREATED_DATETIME,UPDATED_BY_UUID,UPDATED_DATETIME)
   VALUES(UUID(),v_id,'MANUAL_REVIEW','LEDGER_RECONCILIATION_FAILED','00000000-0000-0000-0000-000000000001',UTC_TIMESTAMP(6),'00000000-0000-0000-0000-000000000001',UTC_TIMESTAMP(6));
  ELSEIF v_alert_state='RESOLVED' THEN
   UPDATE ACCOUNT_INTEGRITY_ALERT SET STATE='MANUAL_REVIEW',UPDATED_BY_UUID='00000000-0000-0000-0000-000000000001',UPDATED_DATETIME=UTC_TIMESTAMP(6),ROW_VERSION=ROW_VERSION+1 WHERE ID=v_alert;
  END IF;
  IF v_alert IS NULL OR v_alert_state='RESOLVED' THEN
   CALL FINANCE_AUDIT(v_op,v_program,NULL,NULL,p_account,'ACCOUNT_LEDGER_INTEGRITY_FAILED','MANUAL_REVIEW','DENIED');
   INSERT INTO ERROR_LOGS(UUID,PROGRAM_UUID,CORRELATION_ID,OPERATION_UUID,SERVICE_NAME,ERROR_CODE,ERROR_CATEGORY,SEVERITY,SAFE_MESSAGE,CREATED_DATETIME)
   VALUES(UUID(),v_program,v_op,v_op,'Transactions','LEDGER_RECONCILIATION_FAILED','INTEGRITY','ERROR','Account requires ledger investigation; no balance repaired.',UTC_TIMESTAMP(6));
  END IF;
 END IF;
 COMMIT;
END;
